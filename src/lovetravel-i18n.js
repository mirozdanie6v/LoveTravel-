  function normalize(value){
    const raw=String(value||'').trim().toLowerCase().replace('_','-');
    const short=raw.split('-')[0];
    return SUPPORTED.includes(short)?short:'';
  }

  function locale(){
    let stored='';
    try{ stored=normalize(localStorage.getItem(STORAGE_KEY)); }catch(_){}
    if(stored) return stored;
    const html=normalize(document?.documentElement?.lang);
    return html || 'ru';
  }

  function interpolate(message,vars){
    return String(message??'').replace(/\{([a-zA-Z0-9_]+)\}/g,(_,key)=>
      Object.prototype.hasOwnProperty.call(vars||{},key)?String(vars[key]):'{'+key+'}'
    );
  }

  function selectMessage(entry,currentLocale,vars){
    if(typeof entry==='string') return entry;
    if(!entry || typeof entry!=='object') return '';
    const count=Number(vars?.count);
    if(Number.isFinite(count)){
      const tag=LOCALE_TAGS[currentLocale]||'en-US';
      const category=new Intl.PluralRules(tag).select(count);
      return entry[category] ?? entry.other ?? entry.one ?? '';
    }
    return entry.other ?? entry.one ?? '';
  }

  function t(key,vars={},requestedLocale=''){
    const current=normalize(requestedLocale)||locale();
    const entry=BUNDLES[current]?.[key] ?? BUNDLES.ru?.[key];
    if(entry===undefined) return key;
    return interpolate(selectMessage(entry,current,vars),vars);
  }

  const scopeCache=new Map();
  function scope(prefix){
    const normalized=String(prefix||'').replace(/\.+$/,'');
    if(scopeCache.has(normalized)) return scopeCache.get(normalized);
    const proxy=new Proxy(Object.create(null),{
      get(_target,key){
        if(typeof key==='symbol') return undefined;
        return t(normalized+'.'+String(key));
      }
    });
    scopeCache.set(normalized,proxy);
    return proxy;
  }

  function setLocale(next){
    const normalized=normalize(next)||'ru';
    try{ localStorage.setItem(STORAGE_KEY,normalized); }catch(_){}
    return normalized;
  }

  globalThis.LoveTravelI18n=Object.freeze({
    SUPPORTED,
    BUNDLES,
    normalize,
    locale,
    localeTag:(value='')=>LOCALE_TAGS[normalize(value)||locale()]||'ru-RU',
    setLocale,
    t,
    scope,
  });
