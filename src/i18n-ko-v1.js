  function translateDateTime(text) {
    let out=String(text);
    const months={'янв':'1월','фев':'2월','мар':'3월','апр':'4월','май':'5월','мая':'5월','июн':'6월','июл':'7월','авг':'8월','сен':'9월','сент':'9월','окт':'10월','ноя':'11월','дек':'12월'};
    out=out.replace(/(\d{1,2})[–-](\d{1,2})\s+(янв|фев|мар|апр|май|мая|июн|июл|авг|сен|сент|окт|ноя|дек)(?=$|\s|[·,.)])/gi,(_,a,b,m)=>months[String(m).toLowerCase()]+' '+a+'–'+b+'일');
    out=out.replace(/(\d{1,2})\s+(янв|фев|мар|апр|май|мая|июн|июл|авг|сен|сент|окт|ноя|дек)(?=$|\s|[·,.)])/gi,(_,d,m)=>months[String(m).toLowerCase()]+' '+d+'일');
    out=out.replace(/около/gi,'약').replace(/второго дня/gi,'2일차');
    return out;
  }

  function dynamic(text) {
    let m;
    if((m=text.match(/^(\d+)\s+найдено$/i))) return m[1]+'개 찾음';
    if((m=text.match(/^(\d+)\s+из\s+(\d+)\s+мест$/i))) return m[1]+'/'+m[2]+' 좌석';
    if((m=text.match(/^Групповой от\s+(.+)$/i))) return '그룹 '+m[1]+'부터';
    if((m=text.match(/^Индивидуальный от\s+(.+)$/i))) return '프라이빗 '+m[1]+'부터';
    if((m=text.match(/^от\s+(.+)$/i))) return m[1]+'부터';
    if((m=text.match(/^(\d+)\s+взр\.$/i))) return '성인 '+m[1]+'명';
    if((m=text.match(/^(\d+)\s+дет\.$/i))) return '어린이 '+m[1]+'명';
    if((m=text.match(/^(\d+)\s+мал\.$/i))) return '유아 '+m[1]+'명';
    if((m=text.match(/^(\d+)\s+мест$/i))) return m[1]+'석';
    return text;
  }

  function translateAtomic(text) {
    const s=String(text ?? '').trim();
    if(!s) return s;
    const numbered=s.match(/^(\d+\.\s*)(.+)$/);
    if(numbered) return numbered[1]+translateAtomic(numbered[2]);
    if(TEXT[s]) return TEXT[s];
    if(CITY_CASES[s]) return CITY_CASES[s];
    if(CITY[s]) return CITY[s];
    if(SIMPLE[s]) return SIMPLE[s];
    const d=dynamic(s); if(d!==s) return d;
    const dt=translateDateTime(s); if(dt!==s) return dt;
    const en=EN?.translateAtomic?.(s);
    return en && en!==s ? en : s;
  }

